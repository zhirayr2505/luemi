import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import ts from "typescript";
// The former Stage-A stack-based logger was profile-only and has been deleted.
// A2 must not perform Error().stack, synchronous style reads, or diagnostic logs per paint.
const source=readFileSync(new URL("../apps/web/src/discovery/profile-morph-a2-motion.ts",import.meta.url),"utf8");
const renderer=readFileSync(new URL("../apps/web/src/discovery/ProfileMorphA2.tsx",import.meta.url),"utf8");
assert.ok(!source.includes("Error().stack")&&!source.includes("console.log("));
assert.ok(!source.includes("getBoundingClientRect(")&&!source.includes("setTimeout("));
const paint=renderer.slice(renderer.indexOf("paint.current=p=>"),renderer.indexOf("useLayoutEffect(()=>{",renderer.indexOf("paint.current=p=>")));
assert.ok(!paint.includes("getBoundingClientRect(")&&!paint.includes("setState(")&&!paint.includes("console."));
const compiled=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {ProfileMorphMotion}=await import("data:text/javascript;base64,"+Buffer.from(compiled).toString("base64"));
let now=0,id=0;const jobs=new Map(),samples=[],commits=[];
const clock={now:()=>now,request:fn=>{const k=++id;jobs.set(k,fn);return k},cancel:key=>jobs.delete(key)};
const motion=new ProfileMorphMotion(p=>samples.push(p),clock,p=>commits.push(p));
const tick=delta=>{now+=delta;const list=[...jobs.values()];jobs.clear();for(const fn of list)fn(now);};
motion.settle(1);
tick(30);
const before=motion.snapshot().progress;
assert.ok(before>0&&before<1,"starting tween actually advances");
motion.dragStart(40,250);
assert.ok(Math.abs(motion.snapshot().progress-before)<.001,"interrupt begins at current sampled coordinate");
motion.drag(15);
const after=motion.snapshot().progress;
assert.ok(after<before,"reverse gesture tracks the finger");
motion.release(-1);
for(let j=0;j<40;j++)tick(16.7);
assert.equal(motion.snapshot().progress,0);
assert.deepEqual(commits,[0],"stale endpoint must not commit");
assert.ok(samples.every(x=>Number.isFinite(x)&&x>=0&&x<=1));
motion.dispose();
assert.equal(jobs.size,0,"no frame loop left after disposal");
console.log("PROFILE_A2_NO_STACK_LOGS_AND_INTERRUPT_PASS");
